#!/usr/bin/env bash
# ═══════════════════════════════════════════════════════════════════════════════
# alacritty.sh — Alacritty terminal colour theme target for tuiGen
# ═══════════════════════════════════════════════════════════════════════════════
# Community scaffold: functional, but not part of the maintainer's daily setup,
# so treat the output as a starting point rather than a validated theme.
# Emits an Alacritty colour TOML imported from alacritty.toml.
# ═══════════════════════════════════════════════════════════════════════════════

generate_alacritty() {
    derive_ansi_palette

    local name
    name="$(safe_theme_name)"
    local outfile="${OUTPUT_DIR}/${name}/alacritty/${name}.toml"

    local conf
    conf="$(cat << ALAEOF
# ${THEME_NAME} — Alacritty colour theme
# Generated by tuiGen (https://github.com/XAOSTECH/design-flows)
# Colours derived with pastel (https://github.com/sharkdp/pastel)
#
# Scaffold target — import from alacritty.toml:
#   [general]
#   import = ["~/.config/alacritty/${name}.toml"]

[colors.primary]
foreground = "${TUI_FG}"
background = "${TUI_BG}"

[colors.cursor]
text   = "${TUI_BG}"
cursor = "${TUI_CURSOR}"

[colors.selection]
text       = "${TUI_BG}"
background = "${TUI_SELECTION}"

[colors.normal]
black   = "${TUI_C0}"
red     = "${TUI_C1}"
green   = "${TUI_C2}"
yellow  = "${TUI_C3}"
blue    = "${TUI_C4}"
magenta = "${TUI_C5}"
cyan    = "${TUI_C6}"
white   = "${TUI_C7}"

[colors.bright]
black   = "${TUI_C8}"
red     = "${TUI_C9}"
green   = "${TUI_C10}"
yellow  = "${TUI_C11}"
blue    = "${TUI_C12}"
magenta = "${TUI_C13}"
cyan    = "${TUI_C14}"
white   = "${TUI_C15}"
ALAEOF
)"

    write_target_file "$outfile" "$conf"
    install_to_config "$outfile" "${HOME}/.config/alacritty" "alacritty"
}
