#!/usr/bin/env bash
# ═══════════════════════════════════════════════════════════════════════════════
# kitty.sh — kitty terminal colour theme target for tuiGen
# ═══════════════════════════════════════════════════════════════════════════════
# First-class target. Emits a standalone kitty colour config that is pulled in
# from kitty.conf via `include`. Installs into ~/.config/kitty when present.
# ═══════════════════════════════════════════════════════════════════════════════

generate_kitty() {
    derive_ansi_palette

    local name
    name="$(safe_theme_name)"
    local outfile="${OUTPUT_DIR}/${name}/kitty/${name}.conf"

    local conf
    conf="$(cat << KITTYEOF
# ${THEME_NAME} — kitty colour theme
# Generated by tuiGen (https://github.com/XAOSTECH/design-flows)
# Colours derived with pastel (https://github.com/sharkdp/pastel)
#
# Pull this in from kitty.conf:
#   include ${name}.conf
# For the themes palette cycler, point current-theme.conf at the active theme:
#   include current-theme.conf

foreground ${TUI_FG}
background ${TUI_BG}
cursor     ${TUI_CURSOR}
selection_foreground ${TUI_BG}
selection_background ${TUI_SELECTION}

color0  ${TUI_C0}
color1  ${TUI_C1}
color2  ${TUI_C2}
color3  ${TUI_C3}
color4  ${TUI_C4}
color5  ${TUI_C5}
color6  ${TUI_C6}
color7  ${TUI_C7}
color8  ${TUI_C8}
color9  ${TUI_C9}
color10 ${TUI_C10}
color11 ${TUI_C11}
color12 ${TUI_C12}
color13 ${TUI_C13}
color14 ${TUI_C14}
color15 ${TUI_C15}
KITTYEOF
)"

    write_target_file "$outfile" "$conf"
    install_to_config "$outfile" "${HOME}/.config/kitty" "kitty"
}
