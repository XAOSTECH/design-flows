#!/usr/bin/env bash
# ═══════════════════════════════════════════════════════════════════════════════
# fish.sh — fish shell colour theme target for tuiGen
# ═══════════════════════════════════════════════════════════════════════════════
# Scaffold target (new, not in the maintainer's daily setup). Emits a fish
# colour snippet using `set -g fish_color_*` variables. fish expects bare hex
# (no leading '#'), so the tokens are stripped accordingly.
#
# Source it from config.fish, or drop it into ~/.config/fish/conf.d/ to autoload.
# ═══════════════════════════════════════════════════════════════════════════════

generate_fish() {
    derive_ansi_palette

    local name
    name="$(safe_theme_name)"
    local muted
    muted="${BLEND_COLOURS[0]:-$(mix_colors "$TUI_FG" "$TUI_BG" 0.5)}"

    local outfile="${OUTPUT_DIR}/${name}/fish/${name}.fish"

    local conf
    conf="$(cat << FISHEOF
# ${THEME_NAME} — fish colour theme (scaffold)
# Generated by tuiGen (https://github.com/XAOSTECH/design-flows)
# Colours derived with pastel (https://github.com/sharkdp/pastel)
#
# Autoload by linking into conf.d:
#   ln -s ~/.config/fish/themes/${name}.fish ~/.config/fish/conf.d/${name}.fish

set -g fish_color_normal ${TUI_FG#\#}
set -g fish_color_command ${TUI_C4#\#}
set -g fish_color_keyword ${TUI_C5#\#}
set -g fish_color_quote ${TUI_C2#\#}
set -g fish_color_redirection ${TUI_C6#\#}
set -g fish_color_end ${TUI_C3#\#}
set -g fish_color_error ${TUI_C1#\#}
set -g fish_color_param ${TUI_C7#\#}
set -g fish_color_comment ${muted#\#}
set -g fish_color_selection --background=${TUI_SELECTION#\#}
set -g fish_color_search_match --background=${TUI_SELECTION#\#}
set -g fish_color_operator ${TUI_C6#\#}
set -g fish_color_escape ${TUI_C13#\#}
set -g fish_color_autosuggestion ${muted#\#}
set -g fish_color_cwd ${TUI_C3#\#}
set -g fish_color_user ${TUI_C2#\#}
set -g fish_color_host ${TUI_C4#\#}

set -g fish_pager_color_progress ${muted#\#}
set -g fish_pager_color_prefix ${TUI_C6#\#}
set -g fish_pager_color_completion ${TUI_FG#\#}
set -g fish_pager_color_description ${muted#\#}
set -g fish_pager_color_selected_background --background=${TUI_SELECTION#\#}
FISHEOF
)"

    write_target_file "$outfile" "$conf"
    install_to_config "$outfile" "${HOME}/.config/fish/themes" "fish"
}
