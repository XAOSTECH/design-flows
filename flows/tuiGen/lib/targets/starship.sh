#!/usr/bin/env bash
# ═══════════════════════════════════════════════════════════════════════════════
# starship.sh — Starship prompt palette target for tuiGen
# ═══════════════════════════════════════════════════════════════════════════════
# First-class target. Emits a Starship palette block ([palettes.<name>]) derived
# from the generated palette, plus the one-line selector to activate it.
#
# At rest this is a static, includable palette. The themes palette cycler selects
# between pre-generated palettes at runtime via STARSHIP_CONFIG (no toml mutation),
# so generation (here) and activation (themes) stay cleanly separated.
# ═══════════════════════════════════════════════════════════════════════════════

generate_starship() {
    derive_ansi_palette

    local name primary_hex
    name="$(safe_theme_name)"
    primary_hex=$(get_hex "$PRIMARY_COLOUR")

    local accent muted
    accent="${PRIMARY_SHADES[5]:-$primary_hex}"
    muted="${BLEND_COLOURS[0]:-$(mix_colors "$TUI_FG" "$TUI_BG" 0.5)}"

    local outfile="${OUTPUT_DIR}/${name}/starship/${name}.toml"

    local conf
    conf="$(cat << STARSHIPEOF
# ${THEME_NAME} — Starship prompt palette
# Generated by tuiGen (https://github.com/XAOSTECH/design-flows)
# Colours derived with pastel (https://github.com/sharkdp/pastel)
#
# Activate by selecting this palette at the top of starship.toml:
#   palette = "${name}"
# then paste the block below (or include this file's contents).

palette = "${name}"

[palettes.${name}]
fg       = "${TUI_FG}"
bg       = "${TUI_BG}"
accent   = "${accent}"
muted    = "${muted}"
cursor   = "${TUI_CURSOR}"

black         = "${TUI_C0}"
red           = "${TUI_C1}"
green         = "${TUI_C2}"
yellow        = "${TUI_C3}"
blue          = "${TUI_C4}"
magenta       = "${TUI_C5}"
cyan          = "${TUI_C6}"
white         = "${TUI_C7}"
bright_black   = "${TUI_C8}"
bright_red     = "${TUI_C9}"
bright_green   = "${TUI_C10}"
bright_yellow  = "${TUI_C11}"
bright_blue    = "${TUI_C12}"
bright_magenta = "${TUI_C13}"
bright_cyan    = "${TUI_C14}"
bright_white   = "${TUI_C15}"
STARSHIPEOF
)"

    write_target_file "$outfile" "$conf"

    # Starship has no config subdir convention beyond the single file; install
    # the palette alongside it only when ~/.config exists.
    install_to_config "$outfile" "${HOME}/.config/starship" "starship"
}
