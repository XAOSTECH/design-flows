#!/usr/bin/env bash
# ═══════════════════════════════════════════════════════════════════════════════
# foot.sh — foot terminal colour theme target for tuiGen
# ═══════════════════════════════════════════════════════════════════════════════
# Community scaffold: functional, but not part of the maintainer's daily setup.
# Emits a foot colour include. Note: foot's own config schema spells the section
# [colors] (and expects bare 6-digit hex), so those tokens stay in foot's syntax
# rather than UK spelling.
# ═══════════════════════════════════════════════════════════════════════════════

generate_foot() {
    derive_ansi_palette

    local name
    name="$(safe_theme_name)"
    local outfile="${OUTPUT_DIR}/${name}/foot/${name}.ini"

    local conf
    conf="$(cat << FOOTEOF
# ${THEME_NAME} — foot colour theme
# Generated by tuiGen (https://github.com/XAOSTECH/design-flows)
# Colours derived with pastel (https://github.com/sharkdp/pastel)
#
# Scaffold target — include from foot.ini:
#   include=~/.config/foot/${name}.ini

[cursor]
color=${TUI_BG#\#} ${TUI_CURSOR#\#}

[colors]
foreground=${TUI_FG#\#}
background=${TUI_BG#\#}
selection-foreground=${TUI_BG#\#}
selection-background=${TUI_SELECTION#\#}

regular0=${TUI_C0#\#}
regular1=${TUI_C1#\#}
regular2=${TUI_C2#\#}
regular3=${TUI_C3#\#}
regular4=${TUI_C4#\#}
regular5=${TUI_C5#\#}
regular6=${TUI_C6#\#}
regular7=${TUI_C7#\#}

bright0=${TUI_C8#\#}
bright1=${TUI_C9#\#}
bright2=${TUI_C10#\#}
bright3=${TUI_C11#\#}
bright4=${TUI_C12#\#}
bright5=${TUI_C13#\#}
bright6=${TUI_C14#\#}
bright7=${TUI_C15#\#}
FOOTEOF
)"

    write_target_file "$outfile" "$conf"
    install_to_config "$outfile" "${HOME}/.config/foot" "foot"
}
